export function LanguageProvider({ children }: { children: ReactNode }) {
  const [role, setRole] = useState<Role>(() => {
    const saved = localStorage.getItem("currentRole");
    return (saved === "rider" || saved === "driver" || saved === "admin" ? saved : "rider");
  });

  const [language, setLanguage] = useState<Language>(() => {
    const saved = localStorage.getItem(`${role}_language`);
    return (saved && saved in translations ? saved as Language : "en");
  });

  useEffect(() => {
    localStorage.setItem(`${role}_language`, language);
  }, [language, role]);

  const t = (key: string): string => {
    return translations[language][key] || translations["en"][key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, role, setRole }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
}

